// Generate one browser/Node field guide from the existing machine-readable audit.
const fs = require('node:fs');
const path = require('node:path');
require('../dist/tactical-systems');
const { load } = require('./audit-content.cjs');
const root = path.join(__dirname, '..');
const { schema } = load();
const report = JSON.parse(fs.readFileSync(path.join(root, 'reports/world-database-links.json')));
const entries = {};
for (const [kind, definition] of Object.entries(schema.schemas)) {
  for (const field of definition.fields) {
    const audited = report.catalog.find(row => row.kind === kind && row.key === field.key);
    if (!audited || !audited.note || !audited.status) {
      throw Error('Missing audited explanation: ' + kind + '.' + field.key);
    }
    entries[kind + '.' + field.key] = {
      label: field.label,
      description: [field.label, field.hint || audited.note].join(' — ').replace(/\s+/g, ' '),
      status: audited.status,
      consumer: audited.consumer
    };
  }
}
// fieldsFor() adds this existing adapter field even though the legacy schema lacks it.
entries['accessory.passive'] = {
  label: 'โบนัสตัวเลขที่ใช้จริง',
  description: 'โบนัสตัวเลข เช่น STR +2, HP +10, Crit +5% ตาม parser อุปกรณ์ที่รองรับ',
  status: 'partial',
  consumer: 'dist/legacy-equipment.js#parseEquipmentPassiveEffects'
};
const guide = { source: 'reports/world-database-links.json / WORLD-DATABASE-FIELDS.md', entries };
const code = [
  '// Generated by tools/generate-field-guide.cjs. Do not edit generated entries by hand.',
  '(function (root, factory) {',
  '  const value = factory();',
  "  if (typeof module !== 'undefined') module.exports = value;",
  '  root.DecideFieldGuide = value;',
  "})(typeof window === 'undefined' ? globalThis : window, function () {",
  '  return ' + JSON.stringify(guide, null, 2) + ';',
  '});',
  ''
].join('\n');
fs.writeFileSync(path.join(root, 'dist/field-guide.js'), code);
console.log('Generated field guide: ' + (Object.keys(entries).length - 1) + ' schema fields + existing accessory adapter field');
